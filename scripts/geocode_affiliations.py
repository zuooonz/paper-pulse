def extract_city(affiliation: str) -> tuple[str | None, str | None]:
    """Extract city name from Chinese affiliation string.
    Returns (city_name, province) or (None, None).
    """
    if not affiliation:
        return None, None

    # Try university → city map first (longest name first to avoid partial matches)
    sorted_unis = sorted(UNIVERSITY_CITY_MAP.items(), key=lambda x: -len(x[0]))
    for uni, (city, prov) in sorted_unis:
        if uni in affiliation:
            return city, prov

    # Try extra city map (institution abbreviation → city)
    for abbr, (city, prov) in EXTRA_CITY_MAP.items():
        if abbr in affiliation:
            return city, prov

    # Try city name matching (longer names first to avoid partial matches)
    sorted_cities = sorted(CITY_DB, key=lambda x: -len(x[0]))
    for city, prov, lat, lng in sorted_cities:
        if city in affiliation:
            return city, prov

    return None, None


def main(dry_run: bool = False, workspace: str | Path = ROOT, config_dir: str = "config"):
    session_factory = get_session_factory(str(workspace), config_dir)
    session = session_factory()

    # ── Get all unique Chinese affiliations ─────────────────────────
    affiliations_result = session.execute(text("""
        SELECT DISTINCT affiliation_zh
        FROM authors
        WHERE affiliation_zh IS NOT NULL AND affiliation_zh != ''
        AND affiliation_zh GLOB '*[一-龥]*'
        ORDER BY affiliation_zh
    """))
    affiliations = [r[0] for r in affiliations_result]
    print(f"Unique Chinese affiliations: {len(affiliations)}")

    # ── Geocode each affiliation ────────────────────────────────────
    geocoded = 0
    failed = 0
    results = []

    for aff in affiliations:
        # Sanitize: strip invisible chars
        aff_clean = aff.replace('​', '').replace('‎', '').replace('﻿', '').strip()

        # Check if already geocoded
        exists = session.execute(
            text("SELECT id FROM affiliation_locations WHERE affiliation_zh = :aff"),
            {"aff": aff},
        ).first()
        if exists:
            continue

        city, province = extract_city(aff_clean)

        if city:
            # Look up coordinates
            for c, p, lat, lng in CITY_DB:
                if c == city:
                    if not dry_run:
                        session.execute(
                            text("""
                                INSERT OR IGNORE INTO affiliation_locations
                                (affiliation_zh, city, province, lat, lng, geocoded_at)
                                VALUES (:aff, :city, :province, :lat, :lng, datetime('now'))
                            """),
                            {"aff": aff, "city": city, "province": province, "lat": lat, "lng": lng},
                        )
                    geocoded += 1
                    results.append((aff, city, province, lat, lng))
                    break
            else:
                failed += 1
        else:
            failed += 1
            if failed <= 20:
                # Safe print
                safe_aff = aff.encode('ascii', errors='replace').decode('ascii')[:80]
                print(f"  NO CITY: {safe_aff}")

    if not dry_run:
        session.commit()

    print(f"\nGeocoded (city match): {geocoded}")
    print(f"Failed (no city found): {failed}")
    print(f"Success rate: {geocoded * 100 // max(1, geocoded + failed)}%")

    # ── Verify ──────────────────────────────────────────────────────
    total_locations = session.execute(text("SELECT COUNT(*) FROM affiliation_locations")).scalar_one()
    with_coords = session.execute(
        text("SELECT COUNT(*) FROM affiliation_locations WHERE lat IS NOT NULL")
    ).scalar_one()
    print(f"\nTotal locations in DB: {total_locations}")
    print(f"With coordinates: {with_coords}")

    # ── Summary by city ─────────────────────────────────────────────
    city_rows = session.execute(text("""
        SELECT city, province, COUNT(*) as cnt
        FROM affiliation_locations
        WHERE lat IS NOT NULL
        GROUP BY city, province
        ORDER BY cnt DESC
        LIMIT 15
    """))
    print("\n=== TOP CITIES ===")
    for city, prov, cnt in city_rows:
        print(f"  {city} ({prov}): {cnt} institutions")

    session.close()


